#!/usr/bin/env python3
"""Build data/employment_exposure.yaml: employment growth by AI exposure, twenty bins.

    python3 scripts/refresh_employment_exposure.py      # -> data/employment_exposure.yaml, then build.py

WHAT (ML, 23 Oct 2026). The Outcomes module's chart in the style of Hensvik and Nordström Skans
(2019, Figure 1): Swedish occupations grouped into twenty bins by DAIOE v1.1.0 generative-AI
exposure (g2gen), each bin's employment growth weighted by employment, with the weighted slope
and its 95% interval. Computed in the ai-monitor repo by
demo/employment_by_exposure_g2gen.py from SCB's occupation register (YREG50BAS, SSYK 2012
4-digit) and the published DAIOE bundle; this script only transcribes its output.

WHY 2023-2024. SCB's occupation coding improved in 2023: employed persons with no occupation code
fell from 272,181 (2022) to 41,232 (2023). Growth over any window crossing 2023 mixes real change
with recoding, so the chart starts in 2023 (ai-monitor notes/2026-10-23_occupation-register-
coding-break.md). The window lengthens when SCB publishes the 2025 register. The rising and
declining tails wait for that second clean year (ML, 23 Oct 2026). DO NOT hand-edit the yaml.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = Path(os.environ.get("AIEL_WORKSPACE", ROOT.parents[1]))
BASE = 2023
SRC = (WORKSPACE / "lab-infrastructure/ai-monitor/demo/firm-dimension/insights"
       / f"employment_by_exposure_g2gen_{BASE}.json")
OUT = ROOT / "data" / "employment_exposure.yaml"


def main() -> None:
    d = json.loads(SRC.read_text(encoding="utf-8"))
    assert d["window"].startswith(str(BASE)), f"source window {d['window']} does not start in {BASE}"
    L = ["# Employment growth by AI exposure (Outcomes module). Generated by",
         "# scripts/refresh_employment_exposure.py from ai-monitor demo/employment_by_exposure_g2gen.py.",
         "# Do not hand-edit.",
         "meta:",
         f'  window: "{d["window"].replace("-", "–")}"',
         f'  exposure: "{d["exposure"]}"',
         f'  employment: "{d["employment"]}"',
         f'  n_occ: {d["n_chart"]}',
         f'  mean_growth_pct: {d["mean_growth"] * 100:.4f}',
         f'  slope: {d["slope"]:.6f}',
         f'  slope_lo: {d["slope_lo"]:.6f}',
         f'  slope_hi: {d["slope_hi"]:.6f}',
         "  min_employed: 500",
         "bins:"]
    for b in d["bins"]:
        L.append(f'  - {{bin: {int(b["bin"])}, pctl: {b["x"] * 100:.1f}, growth_pct: {b["y"] * 100:.2f}, '
                 f'employed: {int(b["emp"])}}}')
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    yaml.safe_load(OUT.read_text(encoding="utf-8"))              # refuse to leave a broken file
    print(f"wrote {OUT.name}: {len(d['bins'])} bins, slope {d['slope']:.3f} "
          f"[{d['slope_lo']:.3f}, {d['slope_hi']:.3f}], {d['n_chart']} occupations")


if __name__ == "__main__":
    main()
